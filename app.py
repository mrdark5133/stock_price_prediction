# ----------------------------------------------------------------------
# Load trained pickle model
# ----------------------------------------------------------------------
@st.cache_resource
def load_model():
    with open(MODEL_FILE, "rb") as f:
        artifact = pickle.load(f)

    # Supports the model.pkl generated by the supplied model.py.
    if isinstance(artifact, dict) and "model" in artifact:
        model = artifact["model"]
        feature_cols = artifact.get("feature_cols", FEATURE_COLS)
    else:
        model = artifact
        feature_cols = FEATURE_COLS

    if list(feature_cols) != FEATURE_COLS:
        raise ValueError(
            "The feature columns stored in model.pkl do not match app.py."
        )

    return model


# ----------------------------------------------------------------------
# Data + feature engineering
# ----------------------------------------------------------------------
@st.cache_data(ttl=3600, show_spinner=False)
def fetch_stock_data(ticker: str, start: str) -> pd.DataFrame:
    def clean(d):
        if isinstance(d.columns, pd.MultiIndex):
            d.columns = d.columns.get_level_values(0)
        d.index = pd.to_datetime(d.index).tz_localize(None)
        return d

    df = pd.DataFrame()

    for delay in (0, 3, 6):
        if delay:
            import time
            time.sleep(delay)

        try:
            tk = yf.Ticker(ticker)
            df = clean(tk.history(start=start, auto_adjust=True))

            if df.empty or len(df) < 60:
                full = clean(tk.history(period="max", auto_adjust=True))
                if not full.empty:
                    df = full[full.index >= pd.to_datetime(start)]

            if not df.empty:
                break
        except Exception:
            df = pd.DataFrame()

    if df.empty:
        raise ValueError(
            f"No data found for '{ticker}'. Yahoo Finance may be "
            "temporarily rate-limiting the request."
        )

    df = df[["Open", "High", "Low", "Close", "Volume"]].copy()
    df.dropna(inplace=True)

    return df


def add_features(df: pd.DataFrame) -> pd.DataFrame:
    df = df.copy()

    df["SMA_10"] = ta.trend.sma_indicator(df["Close"], window=10)
    df["SMA_20"] = ta.trend.sma_indicator(df["Close"], window=20)
    df["EMA_10"] = ta.trend.ema_indicator(df["Close"], window=10)
    df["EMA_20"] = ta.trend.ema_indicator(df["Close"], window=20)
    df["RSI_14"] = ta.momentum.rsi(df["Close"], window=14)

    macd = ta.trend.MACD(df["Close"])
    df["MACD"] = macd.macd()
    df["MACD_signal"] = macd.macd_signal()

    bb = ta.volatility.BollingerBands(df["Close"], window=20)
    df["BB_high"] = bb.bollinger_hband()
    df["BB_low"] = bb.bollinger_lband()

    df["Daily_Return"] = df["Close"].pct_change()
    df["Volume_Change"] = df["Volume"].pct_change()

    for lag in (1, 2, 3, 5):
        df[f"Close_lag{lag}"] = df["Close"].shift(lag)

    df.replace([np.inf, -np.inf], np.nan, inplace=True)
    return df


# ----------------------------------------------------------------------
# Evaluation using the loaded model
# ----------------------------------------------------------------------
def evaluate_model(model, df):
    feat_df = add_features(df)
    feat_df["Target"] = feat_df["Close"].shift(-1)
    feat_df.replace([np.inf, -np.inf], np.nan, inplace=True)
    feat_df.dropna(inplace=True)

    if len(feat_df) < 20:
        return None

    X = feat_df[FEATURE_COLS]
    y = feat_df["Target"]

    split_idx = int(len(feat_df) * 0.85)

    X_test = X.iloc[split_idx:]
    y_test = y.iloc[split_idx:]

    if len(X_test) == 0:
        return None

    y_pred = model.predict(X_test)

    metrics = {
        "RMSE": float(np.sqrt(mean_squared_error(y_test, y_pred))),
        "MAE": float(mean_absolute_error(y_test, y_pred)),
        "R2": float(r2_score(y_test, y_pred)),
        "MAPE": float(
            np.mean(np.abs((y_test - y_pred) / y_test)) * 100
        ),
    }

    return (
        metrics,
        feat_df.index[split_idx:],
        y_test.values,
        y_pred,
    )


# ----------------------------------------------------------------------
# Forecast
# ----------------------------------------------------------------------
def forecast_future(model, df, n_days):
    history = df[["Open", "High", "Low", "Close", "Volume"]].copy()
    preds = []

    for _ in range(n_days):
        feat_df = add_features(history)

        last_row = (
            feat_df[FEATURE_COLS]
            .iloc[[-1]]
            .replace([np.inf, -np.inf], np.nan)
        )

        if last_row.isna().any().any():
            last_row = last_row.fillna(
                feat_df[FEATURE_COLS].iloc[-5:].mean()
            )

        next_close = float(model.predict(last_row)[0])

        next_date = history.index[-1] + timedelta(days=1)

        while next_date.weekday() >= 5:
            next_date += timedelta(days=1)

        preds.append((next_date, next_close))

        new_row = pd.DataFrame(
            {
                "Open": [next_close],
                "High": [next_close],
                "Low": [next_close],
                "Close": [next_close],
                "Volume": [history["Volume"].iloc[-1]],
            },
            index=[next_date],
        )

        history = pd.concat([history, new_row])

    return pd.DataFrame(
        preds,
        columns=["Date", "Predicted_Close"],
    )


def get_prediction_for_date(future_df, target_date):
    matches = future_df[future_df["Date"] >= target_date]

    if matches.empty:
        return None, None, False

    row = matches.iloc[0]

    return (
        row["Date"],
        row["Predicted_Close"],
        row["Date"] == target_date,
    )


